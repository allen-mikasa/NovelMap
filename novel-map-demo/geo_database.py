def lookup_location(name: str) -> dict:
    """
    查询地点坐标（虚拟坐标系0-1000）。
    返回: {"x": int, "y": int, "type": str, "region": str} 或 None
    """
    if not name:
        return None
    name = name.strip()

    raw = _lookup_raw(name)
    if not raw:
        return None
    lng, lat, loc_type, region = raw
    xy = _geo_to_xy(lng, lat)
    return {"x": xy[0], "y": xy[1], "lng": lng, "lat": lat, "type": loc_type, "region": region}


def lookup_location_lnglat(name: str) -> dict:
    """
    查询地点的真实经纬度。
    返回: {"lng": float, "lat": float, "type": str, "region": str} 或 None
    """
    if not name:
        return None
    name = name.strip()

    raw = _lookup_raw(name)
    if not raw:
        return None
    lng, lat, loc_type, region = raw
    return {"lng": lng, "lat": lat, "type": loc_type, "region": region}


def _lookup_raw(name: str):
    """内部方法：查询原始数据"""
    if not name:
        return None
    name = name.strip()

    # 精确匹配
    if name in _GEO_RAW:
        return _GEO_RAW[name]

    # 去掉常见后缀再匹配
    suffixes = ["城", "关", "山", "郡", "州", "县", "府", "渡", "口", "原", "坡", "谷"]
    for suffix in suffixes:
        if name.endswith(suffix):
            base = name[:-1]
            if base in _GEO_RAW:
                return _GEO_RAW[base]

    # 包含匹配
    for key, val in _GEO_RAW.items():
        if key in name or name in key:
            return val

    return None


def lookup_batch(locations: list, use_lnglat=False) -> dict:
    """批量查询地点坐标。use_lnglat=True时返回经纬度，否则返回虚拟坐标"""
    result = {}
    for loc in locations:
        name = loc.get("name", "").strip()
        if name and name not in result:
            if use_lnglat:
                geo = lookup_location_lnglat(name)
            else:
                geo = lookup_location(name)
            if geo:
                result[name] = geo
    return result


def detect_factions(locations: list, characters: list) -> list:
    """
    从地点和人物中检测势力/阵营，返回势力列表。
    """
    factions = set()
    for loc in locations:
        belongs = loc.get("belongs_to", "").strip()
        if belongs:
            factions.add(belongs)
    for char in characters:
        faction = char.get("faction", "").strip()
        if faction:
            factions.add(faction)

    # 匹配已知势力
    detected = []
    for faction_name in factions:
        for key in _FACTION_REGIONS:
            if key in faction_name or faction_name in key:
                detected.append({**_FACTION_REGIONS[key], "source": faction_name})
                break

    return detected


def get_region_colors(color_index: int) -> tuple:
    """获取区域颜色"""
    idx = color_index % len(REGION_COLORS)
    return REGION_COLORS[idx], REGION_BORDER_COLORS[idx]
