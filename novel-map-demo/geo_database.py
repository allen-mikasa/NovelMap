# 坐标映射规则（全球）：
# 经度范围 -180° ~ 180° → x: 0 - 1000
# 纬度范围 -60° ~ 80° → y: 0 - 1000 (北在上)
# x = (lng + 180) / 360 * 1000
# y = (80 - lat) / 140 * 1000

def _geo_to_xy(lng, lat):
    x = round((lng + 180) / 360 * 1000)
    y = round((80 - lat) / 140 * 1000)
    return [max(0, min(1000, x)), max(0, min(1000, y))]


